#!/usr/bin/env python3
"""Hooky - one-click audit link layer.

Turns the webhook collector into a self-service audit portal:

1. The auditor generates a ONE-TIME link:  http://<controller>:<port>/go/<token>
2. The link is sent to the Windows user by chat or e-mail - no SSH access,
   no commands to copy, nothing to install on their side.
3. The user clicks the link and sees a consent page in the browser.
4. "I allow" downloads one self-contained file (hooky-audit.cmd) that embeds
   the whole read-only PowerShell agent as base64.
5. Opening the file shows a native Windows permission popup (Yes / No).
6. "Yes" runs the read-only audit (~15-30 s) and POSTs the JSON result back.
7. The collector generates the reports immediately, burns the token and the
   link stops working. No persistent connection exists at any moment.

Everything here is stdlib-only. The HTTP routes are wired in lib/remote.py.
"""

import base64
import os
import re
import secrets
import threading
import time

# Path of the bundled PowerShell agent (hooky/windows/hooky-agent.ps1)
AGENT_PATH = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "windows", "hooky-agent.ps1")

MARKER = "@@HOOKY_PAYLOAD@@"       # separates the batch stub from the payload
DEFAULT_TTL_MIN = 30
CMD_NAME = "hooky-audit.cmd"

COLLECTION_SUMMARY = (
    "system info, user accounts and password policy, security policies, "
    "Windows Defender status, installed antivirus, firewall profile, disk "
    "encryption (BitLocker), patch level, audit policy, listening ports, "
    "services, network shares and domain status")

_B64_WRAP = 200                    # base64 characters per line


def new_token():
    return "hooky-" + secrets.token_hex(8)


# --------------------------------------------------------------------------- #
#  One-time link state
# --------------------------------------------------------------------------- #

class LinkRegistry(object):
    """Holds the ONE live one-click link of a link flow.

    Thread-safe: the HTTP handler threads write events, the main thread
    polls them for the console status lines.
    """

    def __init__(self, ttl_minutes=DEFAULT_TTL_MIN, quick=False, label=""):
        self.token = new_token()
        self.ttl_minutes = max(1, int(ttl_minutes))
        self.ttl_seconds = self.ttl_minutes * 60
        self.quick = bool(quick)
        self.label = label or "your auditor"
        self.created = time.time()
        self.state = "waiting"     # waiting -> opened -> allowed -> used | denied
        self.client_ip = ""
        self._lock = threading.Lock()
        self._events = []

    def live(self):
        return (time.time() - self.created) <= self.ttl_seconds \
            and self.state not in ("used", "denied")

    def gone_reason(self):
        if (time.time() - self.created) > self.ttl_seconds:
            return "it expired"
        return {"used": "the audit was already completed",
                "denied": "the audit was declined"}.get(self.state,
                                                        "it is not active")

    def note(self, text):
        with self._lock:
            self._events.append((time.time(), text))

    def poll_events(self):
        with self._lock:
            evs, self._events = self._events[:], []
        return evs


# --------------------------------------------------------------------------- #
#  The self-contained one-click payload (hooky-audit.cmd)
# --------------------------------------------------------------------------- #

# The .cmd is a batch/powershell polyglot:
#   - cmd.exe runs the top part: a short bootstrap that pulls the base64
#     payload OUT OF THIS VERY FILE and runs it with powershell.
#   - everything after MARKER is base64 and never parsed by cmd.exe because
#     `exit /b 0` stops execution first.
# The payload (a PowerShell script) contains the consent popup plus the whole
# bundled agent, also embedded as base64, so ONE file is enough on Windows.

_PAYLOAD_TEMPLATE = r"""#  Hooky one-click audit - auto-generated by the Hooky collector.
#  Read-only: this file changes NOTHING on the PC. It asks for permission,
#  runs the bundled Hooky agent with live progress and sends ONE JSON
#  report to the auditor, then closes.
param($Uri, $Token)
$ErrorActionPreference = 'Stop'
try {
    Add-Type -AssemblyName System.Windows.Forms | Out-Null
    [System.Windows.Forms.Application]::EnableVisualStyles()
    $label = '__LABEL__'
    $msg = "Your auditor ($label) asks permission to run a READ-ONLY security audit on this PC." + "`n`n" +
           "  -  Nothing is installed and nothing is changed" + "`n" +
           "  -  It usually takes 15-30 seconds" + "`n" +
           "  -  One report is sent back, then this window closes by itself" + "`n`n" +
           "Allow the audit?"
    $ans = [System.Windows.Forms.MessageBox]::Show($msg,
        'Hooky - permission requested', 'YesNo', 'Question', 'Button1')
    if ($ans -ne [System.Windows.Forms.DialogResult]::Yes) { exit 2 }
    $agentB64 = @'
__AGENT_B64__
'@
    $agentPath = Join-Path $env:TEMP ('hooky-agent-' + [guid]::NewGuid().ToString('N') + '.ps1')
    [IO.File]::WriteAllBytes($agentPath,
        [Convert]::FromBase64String(($agentB64 -replace '\s', '')))
    $cli = @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', $agentPath,
             '-Uri', $Uri, '-Token', $Token__QUICK__)
    & powershell.exe @cli
    $rc = $LASTEXITCODE
    Remove-Item -LiteralPath $agentPath -Force -ErrorAction SilentlyContinue
    if ($rc -eq 0) {
        [void][System.Windows.Forms.MessageBox]::Show(
            'Audit complete. The report was sent to your auditor.' + "`n" +
            'You can close this window - thank you!', 'Hooky', 'OK', 'Information')
    } else {
        [void][System.Windows.Forms.MessageBox]::Show(
            ('The audit ran but the report could not be sent (exit code ' + $rc +
             '). Please tell your auditor.'), 'Hooky', 'OK', 'Warning')
    }
    exit $rc
} catch {
    try {
        [void][System.Windows.Forms.MessageBox]::Show(
            ('Hooky error: ' + $_.Exception.Message), 'Hooky', 'OK', 'Error')
    } catch { }
    exit 1
}
"""

_CMD_TEMPLATE = r"""@echo off
title Hooky - one-click security audit
rem Auto-generated by Hooky. Read-only audit: nothing is installed or changed.
set "HOOKY_URI=__URI__"
set "HOOKY_TOKEN=__TOKEN__"
echo.
echo   Hooky - one-click security audit (read-only)
echo   Asking for your permission...
echo.
powershell -NoProfile -ExecutionPolicy Bypass -Command "$raw = [IO.File]::ReadAllText('%~f0'); $m = '@@HO' + 'OKY_PAYLOAD@@'; $i = $raw.IndexOf($m); $b = $raw.Substring($i + $m.Length) -replace '\s', ''; $p = Join-Path $env:TEMP ('hooky-audit-' + [guid]::NewGuid().ToString('N') + '.ps1'); [IO.File]::WriteAllBytes($p, [Convert]::FromBase64String($b)); & powershell -NoProfile -ExecutionPolicy Bypass -File $p -Uri '%HOOKY_URI%' -Token '%HOOKY_TOKEN%'; $rc = $LASTEXITCODE; Remove-Item -LiteralPath $p -Force -ErrorAction SilentlyContinue; exit $rc"
if errorlevel 1 (
  echo.
  echo   The audit ended without sending a report - you can close this window.
  echo   Nothing was changed on your PC.
  pause
)
exit /b 0
@@HOOKY_PAYLOAD@@
__PAYLOAD_B64__
"""


def _wrap64(data_b64):
    return "\n".join(data_b64[i:i + _B64_WRAP]
                     for i in range(0, len(data_b64), _B64_WRAP))


def build_payload_ps1(agent_path=None, label="your auditor", quick=False):
    """Build the inner PowerShell payload: consent popup + embedded agent."""
    agent_path = agent_path or AGENT_PATH
    with open(agent_path, "rb") as fh:
        agent_b64 = base64.b64encode(fh.read()).decode("ascii")
    quick_arg = ", '-Quick'" if quick else ""
    payload = (_PAYLOAD_TEMPLATE
               .replace("__LABEL__", str(label).replace("'", "''"))
               .replace("__AGENT_B64__", _wrap64(agent_b64))
               .replace("__QUICK__", quick_arg))
    if not payload.isascii():
        raise ValueError("one-click payload must stay ASCII")
    return payload


def build_oneclick_cmd(uri, reg, agent_path=None):
    """Build the complete hooky-audit.cmd batch file for one link."""
    payload = build_payload_ps1(agent_path=agent_path, label=reg.label,
                                quick=reg.quick)
    payload_b64 = base64.b64encode(payload.encode("utf-8")).decode("ascii")
    uri = str(uri).replace('"', "").replace("%", "")
    token = str(reg.token).replace('"', "").replace("%", "")
    cmd = (_CMD_TEMPLATE
           .replace("__URI__", uri)
           .replace("__TOKEN__", token)
           .replace("__PAYLOAD_B64__", _wrap64(payload_b64)))
    if cmd.count(MARKER) != 1:
        raise ValueError("payload marker must appear exactly once")
    for line in cmd.splitlines():
        if len(line) > 8000:
            raise ValueError("batch line too long for cmd.exe")
    return cmd


